/** Emits the deterministic frontend boilerplate files. */
export function generateFrontendScaffold(appName: string): ProjectFile[] {
  const packageJson = {
    name: `${appName}-frontend`,
    private: true,
    version: '0.1.0',
    type: 'module',
    scripts: {
      dev: 'vite',
      build: 'tsc -b && vite build',
      preview: 'vite preview',
    },
    dependencies: {
      lucide: '^0.525.0',
      react: '^19.0.0',
      'react-dom': '^19.0.0',
    },
    devDependencies: {
      '@tailwindcss/vite': '^4.0.0',
      '@types/react': '^19.0.0',
      '@types/react-dom': '^19.0.0',
      '@vitejs/plugin-react': '^4.3.0',
      tailwindcss: '^4.0.0',
      typescript: '^5.8.0',
      vite: '^6.0.0',
    },
  };

  const viteConfig = [
    "import { defineConfig } from 'vite';",
    "import react from '@vitejs/plugin-react';",
    "import tailwindcss from '@tailwindcss/vite';",
    '',
    'export default defineConfig({',
    '  plugins: [react(), tailwindcss()],',
    "  server: { port: 5173 },",
    '});',
    '',
  ].join('\n');

  const indexHtml = [
    '<!doctype html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="UTF-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
    `    <title>${appName}</title>`,
    '  </head>',
    '  <body>',
    '    <div id="root"></div>',
    "    <script type=\"module\" src=\"/src/main.tsx\"></script>",
    '  </body>',
    '</html>',
    '',
  ].join('\n');

  return [
    { path: 'frontend/package.json', content: `${JSON.stringify(packageJson, null, 2)}\n` },
    { path: 'frontend/vite.config.ts', content: viteConfig },
    { path: 'frontend/index.html', content: indexHtml },
  ];
}

