/** Emits the deterministic backend boilerplate files. */
export function generateBackendScaffold(appName: string): ProjectFile[] {
  const packageJson = {
    name: `${appName}-backend`,
    private: true,
    version: '0.1.0',
    type: 'module',
    scripts: {
      dev: 'tsx watch src/index.ts',
      build: 'tsc',
      start: 'node dist/index.js',
    },
    dependencies: {
      '@hono/node-server': '^1.14.0',
      'better-sqlite3': '^11.10.0',
      'drizzle-orm': '^0.44.0',
      hono: '^4.7.0',
      zod: '^3.24.0',
    },
    devDependencies: {
      '@types/better-sqlite3': '^7.6.13',
      '@types/node': '^22.0.0',
      tsx: '^4.19.0',
      typescript: '^5.8.0',
    },
  };

  const tsConfig = {
    compilerOptions: {
      target: 'ES2022',
      lib: ['ES2022'],
      module: 'NodeNext',
      moduleResolution: 'NodeNext',
      outDir: 'dist',
      rootDir: 'src',
      strict: true,
      verbatimModuleSyntax: true,
      esModuleInterop: true,
      skipLibCheck: true,
      declaration: true,
      sourceMap: true,
    },
    include: ['src/**/*.ts'],
    exclude: ['node_modules', 'dist'],
  };

  return [
    { path: 'backend/package.json', content: `${JSON.stringify(packageJson, null, 2)}\n` },
    { path: 'backend/tsconfig.json', content: `${JSON.stringify(tsConfig, null, 2)}\n` },
  ];
}

// ---------------------------------------------------------------------------
// Emitter
// ---------------------------------------------------------------------------

/**
 * Assembles the boilerplate scaffolds plus the synthesized files (synthesized
 * entries win on path collisions), and writes the full tree under
 * `targetDir/<appName>`. Returns the list of written file paths relative to
 * the project directory, plus the absolute project directory.
 */
export async function emitProject(
  projectFiles: ProjectFile[],
  targetDir: string,
  appName: string = 'apograph-app',
): Promise<{ writtenFiles: string[]; projectDir: string }> {
  const projectDir = resolve(targetDir);

  const boilerplate: ProjectFile[] = [
    generateDockerCompose(appName),
    generateRootReadme(appName),
    ...generateFrontendScaffold(appName),
    ...generateBackendScaffold(appName),
  ];

  // Merge by path; later entries (synthesized files) take precedence.
  const merged = new Map<string, ProjectFile>();
  for (const file of boilerplate) {
    merged.set(file.path, file);
  }
  for (const file of projectFiles) {
    merged.set(file.path, file);
  }

  const writtenFiles: string[] = [];

  for (const file of merged.values()) {
    const filePath = join(projectDir, file.path);
    await mkdir(dirname(filePath), { recursive: true });
    await writeFile(filePath, file.content, 'utf8');
    writtenFiles.push(file.path);
  }

  return { writtenFiles, projectDir };
}
