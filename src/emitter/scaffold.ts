/**
 * apograph — Project scaffolding & emission (Layer 5: Output).
 *
 * Deterministically generates the root orchestration files (docker-compose,
 * README, frontend/backend scaffolds) and writes the full project tree to
 * disk, with synthesized files taking precedence over boilerplate.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import type { ProjectFile } from '../types.js';

// ---------------------------------------------------------------------------
// Root orchestration files
// ---------------------------------------------------------------------------

/** Emits the root docker-compose.yml orchestrating backend + frontend. */
export function generateDockerCompose(appName: string): ProjectFile {
  const content = [
    `# ${appName} — generated by apograph`,
    'services:',
    '  backend:',
    '    build: ./backend',
    '    ports:',
    '      - "3000:3000"',
    '    volumes:',
    '      - ./backend/sqlite.db:/app/sqlite.db',
    '  frontend:',
    '    build: ./frontend',
    '    ports:',
    '      - "5173:5173"',
    '    environment:',
    '      - VITE_API_URL=http://localhost:3000',
  ].join('\n');

  return { path: 'docker-compose.yml', content };
}

/** Emits the root README documenting architecture and setup. */
export function generateRootReadme(appName: string): ProjectFile {
  const content = [
    `# ${appName}`,
    '',
    'A full-stack application synthesized by **apograph** — an industrial cleanroom',
    'reverse-engineering and code synthesis tool — from a harvested reference app.',
    '',
    '## Architecture',
    '',
    '- **frontend/** — React 19 + Vite + Tailwind CSS. Views were generated from',
    '  harvested accessibility-tree snapshots and design tokens.',
    '- **backend/** — Hono v4 API server on Node.js, persisting to SQLite via',
    '  Drizzle ORM. Routes and validation schemas were inferred from observed',
    '  network traffic.',
    '- **docker-compose.yml** — orchestrates both services end to end.',
    '',
    '## Local Setup',
    '',
    '```bash',
    '# Backend',
    'cd backend && pnpm install && pnpm dev',
    '',
    '# Frontend (separate terminal)',
    'cd frontend && pnpm install && pnpm dev',
    '```',
    '',
    '## Docker Boot',
    '',
    '```bash',
    'docker compose up',
    '```',
    '',
    'The API serves on http://localhost:3000 and the frontend on http://localhost:5173.',
    '',
  ].join('\n');

  return { path: 'README.md', content };
}

